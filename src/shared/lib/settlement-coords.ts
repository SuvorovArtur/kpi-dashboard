/**
 * Получить координаты: сначала по улице (ЖК), потом по н.п.
 * Добавляет случайный разброс чтобы точки не накладывались.
 */
/**
 * Координаты ЖК по ключевым словам в address (когда street отсутствует).
 */
const ADDRESS_KEYWORDS: [string, [number, number]][] = [
  ['Императорские Мытищи',  [55.9580, 37.6810]],
  ['Мытищи-Лайт',           [55.9100, 37.7500]],
  ['Мытищи Лайт',           [55.9100, 37.7500]],
  ['Мытищи-16',             [55.9450, 37.6610]],
  ['Болтино',               [55.9681, 37.6780]],
  ['Пироговский',           [55.9760, 37.7430]],
];

export function getSettlementCoords(
  settlement: string | null | undefined,
  street?: string | null,
  address?: string | null,
): { lat: number; lng: number } | null {
  const jitter = () => (Math.random() - 0.5) * 0.002;

  // 1) По улице (ЖК / шоссе)
  if (street) {
    const streetCoords = STREET_COORDS[street];
    if (streetCoords) return { lat: streetCoords[0] + jitter(), lng: streetCoords[1] + jitter() };
  }

  // 2) По ключевым словам в address (ЖК без улицы)
  if (address) {
    for (const [keyword, coords] of ADDRESS_KEYWORDS) {
      if (address.includes(keyword)) {
        return { lat: coords[0] + jitter(), lng: coords[1] + jitter() };
      }
    }
  }

  // 3) По населённому пункту
  if (!settlement) return null;
  const coords = SETTLEMENT_COORDS[settlement];
  if (!coords) return null;
  const jitterWide = () => (Math.random() - 0.5) * 0.004;
  return { lat: coords[0] + jitterWide(), lng: coords[1] + jitterWide() };
}

/**
 * Извлечь GPS-координаты из текста описания обращения.
 * Ищет паттерн вида 55.123456,37.654321 или 56.xxx,37.xxx
 */
export function extractCoordsFromText(text: string | null | undefined): { lat: number; lng: number } | null {
  if (!text) return null;
  const match = text.match(/(5[56]\.\d{4,})\s*,\s*(3[67]\.\d{4,})/);
  if (!match) return null;
  return { lat: parseFloat(match[1]), lng: parseFloat(match[2]) };
}
