def classify_post(text: str, channel_name: str) -> dict | None:
    """Classify a single news post. Returns dict with classification or None on error."""
    if not text or len(text.strip()) < 20:
        return None

    user_prompt = f"[КАНАЛ: {channel_name} | POST]\n{text[:1500]}"

    try:
        response = httpx.post(
            'https://api.deepseek.com/chat/completions',
            headers={
                'Authorization': f'Bearer {DEEPSEEK_API_KEY}',
                'Content-Type': 'application/json',
            },
            json={
                'model': DEEPSEEK_MODEL,
                'messages': [
                    {'role': 'system', 'content': SYSTEM_PROMPT},
                    {'role': 'user', 'content': user_prompt},
                ],
                'response_format': {'type': 'json_object'},
                'temperature': 0.1,
                'max_tokens': 300,
            },
            timeout=30,
        )
        response.raise_for_status()
        content = response.json()['choices'][0]['message']['content']
        result = json.loads(content)

        # Normalize: old format (relevant) -> new format (is_complaint)
        if 'relevant' in result and 'is_complaint' not in result:
            result['is_complaint'] = result.pop('relevant')

        return result

    except Exception as e:
        print(f"[news] Classification error: {e}")
        return None
